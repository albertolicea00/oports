"""Contract implemented by each operating system adapter."""

from typing import Dict, List, Optional, Protocol

from core.models import Interface, Port


class PlatformAdapter(Protocol):
    def get_computer_name(self) -> str: ...
    def get_default_gateway(self) -> Optional[str]: ...
    def get_active_interfaces(self) -> List[Interface]: ...
    def get_arp_table(self, network) -> Dict[str, dict]: ...
    def ping_command(self, ip: str, count: int = 1, timeout_ms: int = 200) -> List[str]: ...
    def get_local_ports(self) -> List[Port]: ...
    def get_active_connections(self) -> List[dict]: ...
    def get_lease_servers(self, interfaces: List[Interface]) -> Dict[str, str]: ...
